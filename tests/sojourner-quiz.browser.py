"""Browser checks for the story quiz. See docs/sojourner-story-quiz.md."""
import json, os, pathlib, shutil, subprocess, tempfile
from playwright.sync_api import sync_playwright,expect
ROOT=pathlib.Path(__file__).resolve().parents[1]
OUT=pathlib.Path(os.environ.get('QUIZ_ARTIFACT_DIR', str(pathlib.Path(tempfile.gettempdir()) / 'cosmic-juniors-quiz-checks')));OUT.mkdir(parents=True, exist_ok=True)
questions=json.loads(subprocess.check_output(['node','--input-type=module','-e',"import {SOJOURNER_QUIZ} from './lib/sojourner-quiz.ts';console.log(JSON.stringify(SOJOURNER_QUIZ))"],cwd=ROOT,text=True))
base=os.environ.get('QUIZ_BASE_URL', 'http://localhost:3000').rstrip('/')
story=base+'/story/sojourner'
text_story=story+'/text'
quiz_url=story+'#story-quiz'
report=[]
def passed(name):report.append(name);print('PASS',name,flush=True)
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path=os.environ.get('CHROMIUM_PATH') or shutil.which('chromium'),args=['--no-sandbox','--disable-dev-shm-usage'])
 page=browser.new_page(viewport={'width':1440,'height':1100},ignore_https_errors=True)
 errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto(story,wait_until='domcontentloaded')
 quiz=page.get_by_role('region',name='Story quiz',exact=True)
 expect(quiz).to_have_count(0)
 page.locator('.ss-snap-pt:not(.is-activity)').last.evaluate('(marker) => marker.scrollIntoView()')
 last_clip=page.locator('video[src$="/v27.mp4"]')
 expect(last_clip).to_have_js_property('paused',False,timeout=15000)
 expect(page.get_by_role('button',name='Take the quiz')).to_be_in_viewport()
 expect(page.locator('.ss-count')).to_have_text('27 / 27')
 page.locator('.ss-frame').evaluate('(frame) => { window.storyFrame = frame }')
 page.mouse.move(5,550)
 page.mouse.wheel(0,1100)
 expect(quiz.get_by_role('heading',name='Story quiz')).to_be_in_viewport()
 expect(page).to_have_url(story)
 assert quiz.evaluate("(quiz) => quiz.closest('.ss-frame') === window.storyFrame")
 expect(last_clip).to_have_js_property('paused',True)
 passed('Scrolling past the final clip reveals the quiz in the same frame and pauses the clip')
 page.get_by_role('button',name='Previous scene').click()
 page.get_by_role('button',name='Take the quiz').press('Enter')
 expect(page.locator('.ss-activity')).to_be_focused()
 expect(page).to_have_url(story)
 passed('The final scene button also opens the quiz and moves keyboard focus into the frame')
 choices=quiz.get_by_role('group').get_by_role('button')
 previous_question=quiz.get_by_role('button',name='Previous question')
 expect(choices).to_have_count(4)
 expect(previous_question).to_be_disabled()
 expect(page.get_by_role('button',name='Next question')).to_be_disabled()
 page.screenshot(path=str(OUT/'quiz-desktop.png'))
 passed('Initial question has four choices; Next is disabled until answered')
 wrong=(questions[0]['correctIndex']+1)%4
 choices.nth(wrong).click()
 expect(choices.nth(wrong)).to_have_attribute('data-state','wrong')
 expect(choices.nth(wrong)).to_have_css('background-color','rgb(127, 29, 29)')
 assert choices.nth(wrong).locator('svg path').get_attribute('d')=='m6 6 12 12M18 6 6 18'
 expect(choices.nth(questions[0]['correctIndex'])).to_have_attribute('data-state','correct')
 expect(page.get_by_role('status')).to_contain_text("Not quite")
 choices.nth(questions[0]['correctIndex']).evaluate('(e)=>e.click()')
 expect(page.get_by_role('progressbar')).to_have_attribute('aria-valuenow','1')
 expect(page.get_by_text('0 correct',exact=True)).to_be_visible()
 page.screenshot(path=str(OUT/'quiz-wrong.png'))
 passed('Wrong choice turns red with X, correct answer is revealed, and answer cannot be rescored')
 quiz.get_by_role('link',name='Revisit chapter 1').click()
 expect(page).to_have_url(story+'#chapter-1')
 expect(quiz).to_have_count(0)
 page.get_by_role('link',name='Back to quiz').click()
 expect(page).to_have_url(quiz_url)
 expect(quiz.get_by_role('progressbar')).to_have_attribute('aria-valuenow','1')
 passed('Reviewing an earlier chapter stays in the story and preserves the quiz answer')
 next_question=quiz.get_by_role('button',name='Next question')
 question_heading=quiz.locator('#quiz-question-title')
 next_question.click()
 expect(question_heading).to_have_text(questions[1]['question'])
 expect(question_heading).to_be_focused()
 previous_question.press('Enter')
 expect(question_heading).to_have_text(questions[0]['question'])
 expect(question_heading).to_be_focused()
 expect(previous_question).to_be_disabled()
 expect(quiz.get_by_role('progressbar')).to_have_attribute('aria-valuenow','1')
 expect(quiz.get_by_role('group').get_by_role('button').nth(wrong)).to_have_attribute('data-state','wrong')
 next_question.click()
 expect(question_heading).to_have_text(questions[1]['question'])
 expect(next_question).to_be_disabled()
 expect(page).to_have_url(quiz_url)
 passed('Previous question restores the prior answer and Next returns to the unanswered question')
 for i,q in enumerate(questions[1:],1):
  choices=page.get_by_role('group').get_by_role('button')
  expect(choices).to_have_count(4)
  expect(page.get_by_role('progressbar')).to_have_attribute('aria-valuenow',str(i))
  choices.nth(q['correctIndex']).click()
  expect(choices.nth(q['correctIndex'])).to_contain_text('Good job!')
  expect(choices.nth(q['correctIndex'])).to_have_css('background-color','rgb(20, 83, 45)')
  assert choices.nth(q['correctIndex']).locator('svg path').get_attribute('d')=='m5 12 4 4L19 6'
  expect(page.get_by_role('status')).to_contain_text('Good job!')
  if i==1:quiz.screenshot(path=str(OUT/'quiz-correct.png'))
  page.get_by_role('button',name='See results' if i==9 else 'Next question').click()
 expect(page.get_by_role('heading',name='Quiz complete!')).to_be_focused()
 expect(page.get_by_label('9 out of 10 correct',exact=True)).to_be_visible()
 page.get_by_text('Review your 10 answers',exact=True).click()
 expect(page.locator('details ol > li')).to_have_count(10)
 assert quiz.locator('details a').first.get_attribute('href')=='#chapter-1'
 quiz.screenshot(path=str(OUT/'quiz-results.png'))
 passed('All ten questions navigate manually, correct choices turn green with check and Good job, mixed score is 9/10, review has chapter links')
 page.get_by_role('button',name='Try again').click()
 expect(page.get_by_role('progressbar')).to_have_attribute('aria-valuenow','0')
 expect(page.get_by_text('0 correct',exact=True)).to_be_visible()
 expect(page.get_by_role('button',name='Next question')).to_be_disabled()
 for i,q in enumerate(questions):
  page.get_by_role('group').get_by_role('button').nth(q['correctIndex']).click()
  page.get_by_role('button',name='See results' if i==9 else 'Next question').click()
 expect(page.get_by_label('10 out of 10 correct',exact=True)).to_be_visible()
 passed('Retry resets all answers and score; perfect run earns 10/10')
 quiz.get_by_role('link',name='Reread the story').click()
 expect(page).to_have_url(story+'#chapter-1')
 expect(quiz).to_have_count(0)
 page.goto(text_story,wait_until='load')
 expect(page.get_by_role('button',name='Read aloud').last).to_be_visible()
 page.get_by_role('link',name='Take the quiz').click()
 expect(page).to_have_url(text_story+'#story-quiz')
 expect(quiz.get_by_role('heading',name='Story quiz')).to_be_in_viewport()
 quiz.get_by_role('group').get_by_role('button').nth(questions[0]['correctIndex']).click()
 expect(quiz.get_by_role('status')).to_contain_text('Good job!')
 passed('Full-text story includes the quiz and a link to it after the chapters')
 page.goto(base+'/games',wait_until='domcontentloaded')
 expect(page.locator('.game-card').first).to_be_visible()
 expect(page.locator('.game-card').filter(has_text='Story Quiz')).to_have_count(0)
 expect(page.locator('a[href="/games/story-quiz"]')).to_have_count(0)
 page.goto(base+'/story/spirit',wait_until='domcontentloaded')
 expect(quiz).to_have_count(0)
 page.goto(base+'/games/story-quiz',wait_until='domcontentloaded')
 expect(page).to_have_url(quiz_url)
 expect(quiz.get_by_role('heading',name='Story quiz')).to_be_in_viewport()
 passed('The quiz is absent from Games and Spirit, and its old URL redirects to Sojourner’s story')
 for width,height in [(390,844),(320,568),(844,390)]:
  page.set_viewport_size({'width':width,'height':height})
  page.reload(wait_until='domcontentloaded')
  expect(page.locator('.ss-frame').get_by_role('heading',name='Story quiz')).to_be_in_viewport()
  assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'),f'Overflow at {width}'
  assert page.locator('.ss-activity').evaluate('(panel) => panel.scrollWidth <= panel.clientWidth'),f'Quiz overflow at {width}'
  quiz.get_by_role('group').get_by_role('button').nth(wrong).click()
  expect(quiz.get_by_role('status')).to_contain_text('Not quite')
  next_question=quiz.get_by_role('button',name='Next question')
  next_question.scroll_into_view_if_needed()
  expect(next_question).to_be_in_viewport()
  expect(previous_question).to_be_in_viewport()
  page.screenshot(path=str(OUT/f'quiz-mobile-{width}.png'))
  next_question.click()
  expect(quiz.get_by_text('Question 2 of 10')).to_be_in_viewport()
  previous_question.click()
  expect(quiz.get_by_text('Question 1 of 10')).to_be_in_viewport()
  expect(quiz.get_by_role('status')).to_contain_text('Not quite')
 passed('Both question controls fit on phone and landscape layouts and preserve the answer')
 for theme in ['cosmic','ink-sand','juniors','beige','mission','original']:
  page.set_viewport_size({'width':1280,'height':1000})
  page.goto(story+'?theme='+theme+'#story-quiz',wait_until='domcontentloaded')
  page.get_by_role('group').get_by_role('button').nth(questions[0]['correctIndex']).click()
  expect(page.get_by_role('status')).to_contain_text('Good job!')
  expect(page.get_by_role('group').get_by_role('button').nth(questions[0]['correctIndex'])).to_have_css('background-color','rgb(20, 83, 45)')
 passed('Correct-answer green fill is preserved across all six site themes')
 assert not errors,errors
 passed('No uncaught browser errors')
 browser.close()
(OUT/'browser-report.json').write_text(json.dumps(report,indent=2))

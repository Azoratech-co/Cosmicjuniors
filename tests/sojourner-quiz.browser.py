"""Browser checks for the story quiz. See docs/sojourner-story-quiz.md."""
import json, os, pathlib, shutil, subprocess, tempfile
from playwright.sync_api import sync_playwright,expect
ROOT=pathlib.Path(__file__).resolve().parents[1]
OUT=pathlib.Path(os.environ.get('QUIZ_ARTIFACT_DIR', str(pathlib.Path(tempfile.gettempdir()) / 'cosmic-juniors-quiz-checks')));OUT.mkdir(parents=True, exist_ok=True)
questions=json.loads(subprocess.check_output(['node','--input-type=module','-e',"import {SOJOURNER_QUIZ} from './lib/sojourner-quiz.ts';console.log(JSON.stringify(SOJOURNER_QUIZ))"],cwd=ROOT,text=True))
base=os.environ.get('QUIZ_BASE_URL', 'http://localhost:3000').rstrip('/')
report=[]
def passed(name):report.append(name);print('PASS',name,flush=True)
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path=os.environ.get('CHROMIUM_PATH') or shutil.which('chromium'),args=['--no-sandbox','--disable-dev-shm-usage'])
 page=browser.new_page(viewport={'width':1440,'height':1100},ignore_https_errors=True)
 errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto(base+'/games/story-quiz',wait_until='networkidle')
 choices=page.get_by_role('group').get_by_role('button')
 expect(choices).to_have_count(4)
 expect(page.get_by_role('button',name='Next question')).to_be_disabled()
 page.screenshot(path=str(OUT/'quiz-desktop.png'),full_page=True)
 passed('Initial question has four choices; Next is disabled until answered')
 wrong=(questions[0]['correctIndex']+1)%4
 choices.nth(wrong).click()
 expect(choices.nth(wrong)).to_have_attribute('data-state','wrong')
 expect(choices.nth(wrong)).to_have_css('background-color','rgb(127, 29, 29)')
 assert choices.nth(wrong).locator('svg path').get_attribute('d')=='m6 6 12 12M18 6 6 18'
 expect(choices.nth(questions[0]['correctIndex'])).to_have_attribute('data-state','correct')
 expect(page.get_by_role('status')).to_contain_text("Not quite")
 choices.nth(questions[0]['correctIndex']).evaluate('(e)=>e.click()')
 expect(page.get_by_role('progressbar')).to_have_attribute('aria-valuenow','1')
 expect(page.get_by_text('0 correct',exact=True)).to_be_visible()
 page.screenshot(path=str(OUT/'quiz-wrong.png'),full_page=True)
 passed('Wrong choice turns red with X, correct answer is revealed, and answer cannot be rescored')
 page.get_by_role('button',name='Next question').click()
 expect(page.locator('#quiz-question-title')).to_be_focused()
 for i,q in enumerate(questions[1:],1):
  choices=page.get_by_role('group').get_by_role('button')
  expect(choices).to_have_count(4)
  expect(page.get_by_role('progressbar')).to_have_attribute('aria-valuenow',str(i))
  choices.nth(q['correctIndex']).click()
  expect(choices.nth(q['correctIndex'])).to_contain_text('Good job!')
  expect(choices.nth(q['correctIndex'])).to_have_css('background-color','rgb(20, 83, 45)')
  assert choices.nth(q['correctIndex']).locator('svg path').get_attribute('d')=='m5 12 4 4L19 6'
  expect(page.get_by_role('status')).to_contain_text('Good job!')
  if i==1:page.screenshot(path=str(OUT/'quiz-correct.png'),full_page=True)
  page.get_by_role('button',name='See results' if i==9 else 'Next question').click()
 expect(page.get_by_role('heading',name='Quiz complete!')).to_be_focused()
 expect(page.get_by_label('9 out of 10 correct',exact=True)).to_be_visible()
 page.get_by_text('Review your 10 answers',exact=True).click()
 expect(page.locator('details ol > li')).to_have_count(10)
 assert page.locator('details a').first.get_attribute('href')=='/story/sojourner/text#chapter-1'
 page.screenshot(path=str(OUT/'quiz-results.png'),full_page=True)
 passed('All ten questions navigate manually, correct choices turn green with check and Good job, mixed score is 9/10, review has chapter links')
 page.get_by_role('button',name='Try again').click()
 expect(page.get_by_role('progressbar')).to_have_attribute('aria-valuenow','0')
 expect(page.get_by_text('0 correct',exact=True)).to_be_visible()
 expect(page.get_by_role('button',name='Next question')).to_be_disabled()
 for i,q in enumerate(questions):
  page.get_by_role('group').get_by_role('button').nth(q['correctIndex']).click()
  page.get_by_role('button',name='See results' if i==9 else 'Next question').click()
 expect(page.get_by_label('10 out of 10 correct',exact=True)).to_be_visible()
 passed('Retry resets all answers and score; perfect run earns 10/10')
 page.get_by_role('link',name='Exit quiz').click()
 expect(page).to_have_url(base+'/story/sojourner/text')
 expect(page.get_by_role('link',name='Take the story quiz · 10 questions')).to_have_count(1)
 page.get_by_role('link',name='Take the story quiz · 10 questions').click()
 expect(page).to_have_url(base+'/games/story-quiz')
 page.get_by_role('link',name='Exit quiz').click()
 expect(page).to_have_url(base+'/story/sojourner/text')
 passed('Exit works from results and before answering; full-story quiz link opens the game')
 page.goto(base+'/games',wait_until='networkidle')
 expect(page.get_by_role('link').filter(has_text='Sojourner Story Quiz')).to_have_count(1)
 page.goto(base+'/story/sojourner',wait_until='domcontentloaded')
 expect(page.get_by_role('link',name='Take the story quiz · 10 questions')).to_have_count(1)
 passed('Games hub and scrolling story link to the quiz')
 for width,height in [(390,844),(320,568),(844,390)]:
  page.set_viewport_size({'width':width,'height':height})
  page.goto(base+'/games/story-quiz',wait_until='networkidle')
  assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'),f'Overflow at {width}'
  page.get_by_role('group').get_by_role('button').nth(0).click()
  expect(page.get_by_role('status')).to_contain_text('Not quite')
  page.get_by_role('button',name='Next question').scroll_into_view_if_needed()
  exit=page.get_by_role('link',name='Exit quiz')
  print('Exit at',width,exit.bounding_box(),flush=True)
  box=exit.bounding_box();assert box['y']>=0 and box['y']+box['height']<=height,'Exit not visible after scrolling'
  page.screenshot(path=str(OUT/f'quiz-mobile-{width}.png'))
  page.get_by_role('link',name='Exit quiz').click();expect(page).to_have_url(base+'/story/sojourner/text')
 passed('Phone and landscape layouts fit without overflow; exit remains visible while scrolling and after a wrong answer')
 for theme in ['cosmic','ink-sand','juniors','beige','mission','original']:
  page.set_viewport_size({'width':1280,'height':1000})
  page.goto(base+'/games/story-quiz?theme='+theme,wait_until='networkidle')
  page.get_by_role('group').get_by_role('button').nth(questions[0]['correctIndex']).click()
  expect(page.get_by_role('status')).to_contain_text('Good job!')
  expect(page.get_by_role('group').get_by_role('button').nth(1)).to_have_css('background-color','rgb(20, 83, 45)')
 passed('Correct-answer green fill is preserved across all six site themes')
 assert not errors,errors
 passed('No uncaught browser errors')
 browser.close()
(OUT/'browser-report.json').write_text(json.dumps(report,indent=2))
